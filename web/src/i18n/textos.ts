const TEXTOS: Record<Idioma, Dicionario> = { pt, es, en };

/**
 * A frase no idioma pedido. Falta em `es`/`en` cai pra `pt`; falta em `pt` devolve a
 * chave -- visível na tela de propósito, porque chave crua é bug que precisa aparecer.
 * `{nome}` no texto é trocado por `vars.nome`.
 */
export function traduzir(idioma: Idioma, chave: string, vars?: Record<string, string | number>): string {
  const base = TEXTOS[idioma][chave] ?? TEXTOS.pt[chave] ?? chave;
  if (!vars) return base;
  return base.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Se existe tradução pra chave, em qualquer idioma que não seja o padrão. Pra saber o que falta. */
export function temTraducao(chave: string, idioma: Idioma): boolean {
  return chave in TEXTOS[idioma];
}
